/**
 * A 16×16 pixel icon drawn with integer-aligned rects in `currentColor`.
 * Icons are decorative by default; pass `title` to expose one to assistive tech.
 */
export default function PixelIcon({name, size = 18, className, title}: PixelIconProps) {
	const rows = ICONS[name];

	return (
		<svg
			className={className}
			width={size}
			height={size}
			viewBox="0 0 16 16"
			fill="currentColor"
			shapeRendering="crispEdges"
			role={title ? 'img' : undefined}
			aria-hidden={title ? undefined : 'true'}
			aria-label={title}
			focusable="false"
		>
			{title ? <title>{title}</title> : null}
			{rows.flatMap((row, y) =>
				[...row].map((cell, x) =>
					cell === '#' ? (
						<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />
					) : null,
				),
			)}
		</svg>
	);
}
